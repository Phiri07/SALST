def outside(f,lat,lon):
 if f['shape']=='rectangle':return not(f['south']<=lat<=f['north'] and f['west']<=lon<=f['east'])
 a=math.radians(lat-f['lat']);b=math.radians(lon-f['lon']);q=math.sin(a/2)**2+math.cos(math.radians(lat))*math.cos(math.radians(f['lat']))*math.sin(b/2)**2
 return 6371000*2*math.asin(min(1,math.sqrt(q)))>f['radius']
