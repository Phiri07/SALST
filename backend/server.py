def format_interval(seconds):
 seconds=int(seconds)
 if seconds>=86400 and seconds%86400==0:return f'{seconds//86400}d'
 if seconds>=3600 and seconds%3600==0:return f'{seconds//3600}h'
 if seconds>=60 and seconds%60==0:return f'{seconds//60}m'
 if seconds>=3600:return f'{seconds//3600}h {(seconds%3600)//60}m' if seconds%3600>=60 else f'{seconds//3600}h {seconds%60}s'
 if seconds>=60:return f'{seconds//60}m {seconds%60}s'
 return f'{seconds}s'
